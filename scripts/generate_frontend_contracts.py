"""Generate deterministic TypeScript from this checkout's FastAPI OpenAPI.

Run from the root: python scripts/generate_frontend_contracts.py [--check]
No server, database query, credentials output, npm package or network needed.
"""
import argparse
from importlib import metadata
import os
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
# Schema inspection must never require a configured development database.
os.environ['APP_ENV'] = 'test'
os.environ['DATABASE_URL'] = 'sqlite:///:memory:'

SCHEMA_PACKAGES = ("fastapi", "starlette", "pydantic", "pydantic_core")


class ContractRuntimeMismatch(RuntimeError):
    """The installed schema toolchain cannot verify this checkout's contract."""


def require_contract_runtime():
    pins = {}
    for line in (ROOT / "backend" / "requirements.txt").read_text(encoding="utf-8").splitlines():
        name, separator, version = line.strip().partition("==")
        if separator and name in SCHEMA_PACKAGES:
            pins[name] = version
    mismatches = []
    for name in SCHEMA_PACKAGES:
        if name not in pins:
            raise ContractRuntimeMismatch(f"Contract verification BLOCKED: missing exact pin for {name}")
        try:
            actual = metadata.version(name)
        except metadata.PackageNotFoundError:
            actual = "not installed"
        if actual != pins[name]:
            mismatches.append(f"{name}: expected {pins[name]}, found {actual}")
    if mismatches:
        raise ContractRuntimeMismatch(
            "Contract verification BLOCKED: schema runtime differs from backend/requirements.txt; "
            + "; ".join(mismatches) + ". No contract output was written."
        )


def literal(value):
    return json.dumps(value, ensure_ascii=True)

def ts(schema):
    if not schema: return 'unknown'
    if '$ref' in schema: return 'ApiSchemas[' + literal(schema['$ref'].split('/')[-1]) + ']'
    if 'const' in schema: return literal(schema['const'])
    if 'enum' in schema: return ' | '.join(literal(v) for v in schema['enum'])
    for key, join in [('anyOf', ' | '), ('oneOf', ' | '), ('allOf', ' & ')]:
        if key in schema: return '(' + join.join(ts(v) for v in schema[key]) + ')'
    kind = schema.get('type')
    if kind == 'null': return 'null'
    if kind in ('number', 'integer'): return 'number'
    if kind in ('string', 'boolean'): return kind
    if kind == 'array': return '(' + ts(schema.get('items', {})) + ')[]'
    if kind == 'object' or 'properties' in schema:
        required = schema.get('required', [])
        fields = [literal(k) + ('' if k in required else '?') + ': ' + ts(v) + ';' for k, v in schema.get('properties', {}).items()]
        extra = schema.get('additionalProperties')
        if extra: fields.append('[key: string]: ' + (ts(extra) if isinstance(extra, dict) else 'unknown') + ';')
        return '{ ' + ' '.join(fields) + ' }' if fields else 'Record<string, unknown>'
    if kind is None and 'properties' not in schema: return 'unknown'
    raise ValueError(f'Unsupported OpenAPI schema: {schema}')

def generate():
    require_contract_runtime()
    from app.main import app
    spec = app.openapi()
    lines = ['// Generated by scripts/generate_frontend_contracts.py. Do not edit.',
             '// Pydantic response Decimal fields serialize to strings; input accepts number|string.',
             'export interface ApiSchemas {']
    lines += ['  ' + literal(name) + ': ' + ts(value) + ';' for name, value in sorted(spec['components']['schemas'].items())]
    lines.append('}\nexport interface ApiOperations {')
    for path, methods in sorted(spec['paths'].items()):
        for method, operation in sorted(methods.items()):
            if method not in ('get','post','put','patch','delete'): continue
            params = operation.get('parameters', [])
            query = {'type':'object','properties':{v['name']:v['schema'] for v in params if v['in']=='query'},'required':[v['name'] for v in params if v['in']=='query' and v.get('required')]}
            request = operation.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema',{})
            responses = operation.get('responses', {})
            response = next((v.get('content',{}).get('application/json',{}).get('schema',{}) for k,v in responses.items() if k.startswith('2')), {})
            lines.append('  '+literal(method.upper()+' '+path)+': { query: '+ts(query)+'; body: '+ts(request)+'; response: '+ts(response)+'; };')
    lines.append('}\n')
    return '\n'.join(lines).replace('\\n', '\n')

def main(argv=None):
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    target=ROOT/'frontend/src/generated/api.ts'
    try:
        output=generate()
    except ContractRuntimeMismatch as exc:
        raise SystemExit(str(exc)) from None
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != output:
            raise SystemExit('Frontend contracts are stale. Run python scripts/generate_frontend_contracts.py')
        print('Frontend contracts match FastAPI OpenAPI.')
    else:
        target.parent.mkdir(parents=True,exist_ok=True);target.write_text(output,encoding='utf-8');print('Generated frontend API contracts.')


if __name__ == '__main__':
    main()
